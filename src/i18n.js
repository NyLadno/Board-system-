const dicts = { ru: RU, en: EN };
export const DICTS = dicts;
let lang = 'ru';

export function setLang(l) { lang = dicts[l] ? l : 'en'; }
export function detectLang() { return (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en'; }
export function getLang() { return lang; }

export function list(key) { return dicts[lang][key] ?? EN[key] ?? []; }

export function t(key, vars) {
  let s = dicts[lang][key] ?? EN[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
